//! zwinger's trusted base is computed, never typed (gale's trusted-base gate, gale#467).
//!
//! The block between the markers in docs/trusted-base.md is rendered from the source and the
//! dependency tree. This test fails when the doc differs by a single character, so the stated
//! trusted base cannot fall behind the code. To update the doc after a reviewed change:
//!
//!     ZWINGER_WRITE_TRUSTED_BASE=1 cargo test --test trusted_base
//!
//! Counted in src/**/*.rs, over text with comments and string literals blanked:
//! - `unsafe` tokens, `extern "C"` blocks and `#[allow(unsafe_code)]` sites (the crate denies
//!   unsafe code everywhere else, so the compiler enforces the boundary);
//! - Verus trust units: `external_body`, `assume_specification` and `assume(` outside Kani;
//! - Kani assumptions (`kani::assume`) and unwinding bounds (`kani::unwind`), which bound what
//!   the bounded proofs cover.
//!
//! Listed from `cargo tree -e normal --target all`: every crate that is compiled into zwinger
//! or runs while it is compiled (proc-macros), on any target.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::process::Command;

const DOC: &str = "docs/trusted-base.md";
const BEGIN: &str = "<!-- trusted-base:begin (generated by tests/trusted_base.rs; do not edit) -->";
const END: &str = "<!-- trusted-base:end -->";

/// Replace comments and the contents of string and char literals with spaces, keeping newlines,
/// so a token in a comment or a string is not counted.
fn blank(src: &str) -> String {
    let b = src.as_bytes();
    let mut out = Vec::with_capacity(b.len());
    let mut i = 0;
    let keep_nl = |c: u8| if c == b'\n' { b'\n' } else { b' ' };
    while i < b.len() {
        let c = b[i];
        let next = b.get(i + 1).copied();
        if c == b'/' && next == Some(b'/') {
            while i < b.len() && b[i] != b'\n' {
                out.push(b' ');
                i += 1;
            }
        } else if c == b'/' && next == Some(b'*') {
            let mut depth = 0usize;
            while i < b.len() {
                if b[i] == b'/' && b.get(i + 1) == Some(&b'*') {
                    depth += 1;
                    out.extend([b' ', b' ']);
                    i += 2;
                } else if b[i] == b'*' && b.get(i + 1) == Some(&b'/') {
                    depth -= 1;
                    out.extend([b' ', b' ']);
                    i += 2;
                    if depth == 0 {
                        break;
                    }
                } else {
                    out.push(keep_nl(b[i]));
                    i += 1;
                }
            }
        } else if c == b'r' && (next == Some(b'"') || next == Some(b'#')) && !ident_before(b, i) {
            // Raw string r"..." or r#"..."#.
            let mut j = i + 1;
            let mut hashes = 0;
            while b.get(j) == Some(&b'#') {
                hashes += 1;
                j += 1;
            }
            if b.get(j) != Some(&b'"') {
                out.push(c);
                i += 1;
                continue;
            }
            out.resize(out.len() + (j + 1 - i), b' ');
            i = j + 1;
            loop {
                if i >= b.len() {
                    break;
                }
                if b[i] == b'"'
                    && b[i + 1..].iter().take(hashes).all(|&h| h == b'#')
                    && b.len() >= i + 1 + hashes
                {
                    out.resize(out.len() + 1 + hashes, b' ');
                    i += 1 + hashes;
                    break;
                }
                out.push(keep_nl(b[i]));
                i += 1;
            }
        } else if c == b'"' {
            out.push(b' ');
            i += 1;
            while i < b.len() && b[i] != b'"' {
                if b[i] == b'\\' && i + 1 < b.len() {
                    out.extend([b' ', keep_nl(b[i + 1])]);
                    i += 2;
                } else {
                    out.push(keep_nl(b[i]));
                    i += 1;
                }
            }
            if i < b.len() {
                out.push(b' ');
                i += 1;
            }
        } else if c == b'\'' && is_char_literal(b, i) {
            let end = char_literal_end(b, i);
            out.resize(out.len() + (end - i), b' ');
            i = end;
        } else {
            out.push(c);
            i += 1;
        }
    }
    String::from_utf8(out).expect("blanking keeps UTF-8 boundaries: only ASCII is replaced")
}

fn ident_before(b: &[u8], i: usize) -> bool {
    i > 0 && (b[i - 1].is_ascii_alphanumeric() || b[i - 1] == b'_')
}

/// A char literal ('a', '\n', '\'', '\u{..}') rather than a lifetime ('a).
fn is_char_literal(b: &[u8], i: usize) -> bool {
    match (b.get(i + 1), b.get(i + 2)) {
        (Some(b'\\'), _) => true,
        (Some(_), Some(b'\'')) => true,
        _ => false,
    }
}

fn char_literal_end(b: &[u8], i: usize) -> usize {
    let mut j = i + 1;
    if b[j] == b'\\' {
        j += 2;
    } else {
        j += 1;
    }
    while j < b.len() && b[j] != b'\'' {
        j += 1;
    }
    (j + 1).min(b.len())
}

/// Occurrences of `word` not preceded or followed by an identifier character.
fn count_word(text: &str, word: &str) -> usize {
    let b = text.as_bytes();
    text.match_indices(word)
        .filter(|(at, _)| {
            let before = *at == 0 || !is_ident(b[at - 1]);
            let end = at + word.len();
            let after = end >= b.len() || !is_ident(b[end]);
            before && after
        })
        .count()
}

fn is_ident(c: u8) -> bool {
    c.is_ascii_alphanumeric() || c == b'_'
}

/// Counts that ignore whitespace inside the pattern, like `#[allow( unsafe_code )]`.
fn count_squashed(text: &str, pattern: &str) -> usize {
    let squashed: String = text.chars().filter(|c| !c.is_whitespace()).collect();
    squashed.matches(pattern).count()
}

#[derive(Default)]
struct Counts {
    unsafe_tokens: usize,
    extern_c: usize,
    allow_unsafe: usize,
    external_body: usize,
    assume_spec: usize,
    verus_assume: usize,
    kani_assume: usize,
    kani_unwind: usize,
}

fn count(src: &str) -> Counts {
    let t = blank(src);
    // `extern "C"` loses its string to blanking; count `extern` followed by a blanked literal.
    let extern_c = src_extern_c(src, &t);
    let kani_assume = count_squashed(&t, "kani::assume(");
    let all_assume = t
        .match_indices("assume(")
        .filter(|(at, _)| *at == 0 || !is_ident(t.as_bytes()[at - 1]))
        .count();
    Counts {
        unsafe_tokens: count_word(&t, "unsafe"),
        extern_c,
        allow_unsafe: count_squashed(&t, "#[allow(unsafe_code)]"),
        external_body: count_squashed(&t, "#[verifier::external_body]")
            + count_squashed(&t, "#[verifier(external_body)]"),
        assume_spec: count_word(&t, "assume_specification"),
        verus_assume: all_assume.saturating_sub(kani_assume),
        kani_assume,
        kani_unwind: count_squashed(&t, "#[kani::unwind("),
    }
}

/// `extern "C"` in code: the token `extern` in the blanked text where the original text
/// continues with `"C"`.
fn src_extern_c(src: &str, blanked: &str) -> usize {
    let b = blanked.as_bytes();
    blanked
        .match_indices("extern")
        .filter(|(at, _)| {
            let before = *at == 0 || !is_ident(b[at - 1]);
            before && src[at + 6..].trim_start().starts_with("\"C\"")
        })
        .count()
}

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn rust_files(dir: &Path, out: &mut Vec<PathBuf>) {
    let mut entries: Vec<_> = std::fs::read_dir(dir)
        .unwrap_or_else(|e| panic!("{}: {e}", dir.display()))
        .map(|e| e.unwrap().path())
        .collect();
    entries.sort();
    for p in entries {
        if p.is_dir() {
            rust_files(&p, out);
        } else if p.extension().is_some_and(|e| e == "rs") {
            out.push(p);
        }
    }
}

fn dependencies() -> Vec<String> {
    let cargo = std::env::var("CARGO").unwrap_or_else(|_| "cargo".into());
    let out = Command::new(cargo)
        .current_dir(root())
        .args([
            "tree", "-e", "normal", "--target", "all", "--prefix", "none",
        ])
        .args(["--format", "{p}", "--locked", "--color", "never"])
        .output()
        .expect("run cargo tree");
    assert!(
        out.status.success(),
        "cargo tree failed: {}",
        String::from_utf8_lossy(&out.stderr)
    );
    let mut deps: Vec<String> = String::from_utf8(out.stdout)
        .unwrap()
        .lines()
        .map(|l| l.trim_end_matches(" (*)").to_string())
        .filter(|l| !l.is_empty() && !l.starts_with("zwinger v"))
        .collect();
    deps.sort();
    deps.dedup();
    deps
}

fn render() -> String {
    let mut files = Vec::new();
    rust_files(&root().join("src"), &mut files);
    assert!(
        !files.is_empty(),
        "read no source file: an empty scan is not an empty trusted base"
    );
    let mut rows: BTreeMap<String, Counts> = BTreeMap::new();
    let mut total = Counts::default();
    for f in &files {
        let c = count(&std::fs::read_to_string(f).unwrap());
        for (sum, v) in [
            (&mut total.unsafe_tokens, c.unsafe_tokens),
            (&mut total.extern_c, c.extern_c),
            (&mut total.allow_unsafe, c.allow_unsafe),
            (&mut total.external_body, c.external_body),
            (&mut total.assume_spec, c.assume_spec),
            (&mut total.verus_assume, c.verus_assume),
            (&mut total.kani_assume, c.kani_assume),
            (&mut total.kani_unwind, c.kani_unwind),
        ] {
            *sum += v;
        }
        let rel = f
            .strip_prefix(root())
            .unwrap()
            .to_string_lossy()
            .replace('\\', "/");
        rows.insert(rel, c);
    }
    let deps = dependencies();
    assert!(!deps.is_empty(), "cargo tree listed no dependency");

    let mut s = String::new();
    s.push_str(&format!(
        "{} source files scanned in `src/`.\n\n",
        files.len()
    ));
    s.push_str("| File | `unsafe` | `extern \"C\"` | `allow(unsafe_code)` | Verus `external_body` | Verus `assume_specification` | Verus `assume` | `kani::assume` | `kani::unwind` |\n");
    s.push_str("|---|---|---|---|---|---|---|---|---|\n");
    let line = |name: &str, c: &Counts| {
        format!(
            "| {name} | {} | {} | {} | {} | {} | {} | {} | {} |\n",
            c.unsafe_tokens,
            c.extern_c,
            c.allow_unsafe,
            c.external_body,
            c.assume_spec,
            c.verus_assume,
            c.kani_assume,
            c.kani_unwind
        )
    };
    for (name, c) in &rows {
        let any = c.unsafe_tokens
            + c.extern_c
            + c.allow_unsafe
            + c.external_body
            + c.assume_spec
            + c.verus_assume
            + c.kani_assume
            + c.kani_unwind;
        if any > 0 {
            s.push_str(&line(&format!("`{name}`"), c));
        }
    }
    s.push_str(&line("**total**", &total));
    s.push_str(&format!(
        "\n{} crates are compiled into zwinger or run while it is compiled (`cargo tree -e normal --target all`):\n\n",
        deps.len()
    ));
    for d in &deps {
        s.push_str(&format!("- `{d}`\n"));
    }
    s
}

#[test]
fn trusted_base_doc_matches_the_source() {
    let path = root().join(DOC);
    let doc = std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("{DOC}: {e}"));
    let start = doc.find(BEGIN).expect("begin marker") + BEGIN.len();
    let end = doc.find(END).expect("end marker");
    assert!(start <= end, "markers out of order");
    let want = format!("\n{}", render());
    if doc[start..end] == want {
        return;
    }
    if std::env::var_os("ZWINGER_WRITE_TRUSTED_BASE").is_some() {
        let new = format!("{}{}{}", &doc[..start], want, &doc[end..]);
        std::fs::write(&path, new).unwrap();
        return;
    }
    panic!(
        "{DOC} is out of date with the source. Review the change to the trusted base, then run \
         ZWINGER_WRITE_TRUSTED_BASE=1 cargo test --test trusted_base\n--- doc\n{}\n--- source\n{}",
        &doc[start..end],
        want
    );
}

#[test]
fn unsafe_code_is_allowed_only_in_the_two_system_modules() {
    let mut files = Vec::new();
    rust_files(&root().join("src"), &mut files);
    let with_allow: Vec<String> = files
        .iter()
        .filter(|f| count(&std::fs::read_to_string(f).unwrap()).allow_unsafe > 0)
        .map(|f| f.file_name().unwrap().to_string_lossy().into_owned())
        .collect();
    assert_eq!(with_allow, ["linux.rs", "macos.rs"]);
    let lib = std::fs::read_to_string(root().join("src/lib.rs")).unwrap();
    assert!(
        blank(&lib).contains("#![deny(unsafe_code)]"),
        "lib.rs must deny unsafe code"
    );
}

// The counters themselves: each one must count code and ignore comments and strings.

#[test]
fn counters_ignore_comments_and_strings() {
    let src = r##"
        // unsafe in a line comment
        /* unsafe in a /* nested */ block comment */
        let s = "unsafe { } kani::assume(x) #[allow(unsafe_code)]";
        let r = r#"unsafe "quoted" assume("#;
        let c = '"';
        fn f<'a>(x: &'a u8) {}
    "##;
    let c = count(src);
    assert_eq!(c.unsafe_tokens, 0);
    assert_eq!(c.allow_unsafe, 0);
    assert_eq!(c.kani_assume, 0);
    assert_eq!(c.verus_assume, 0);
}

#[test]
fn counters_count_code() {
    let src = r#"
        #[allow(unsafe_code)]
        mod sys {
            unsafe extern "C" { fn f(); }
            pub fn g() { unsafe { f() } }
        }
        fn not_unsafe_word() { let unsafely = 1; }
        #[kani::unwind(5)]
        fn h() { kani::assume(true); }
        verus! { proof fn p() { assume(false); } }
        #[verifier::external_body]
        fn e() {}
        pub assume_specification[ std::mem::swap ];
    "#;
    let c = count(src);
    assert_eq!(c.unsafe_tokens, 2);
    assert_eq!(c.extern_c, 1);
    assert_eq!(c.allow_unsafe, 1);
    assert_eq!(c.kani_unwind, 1);
    assert_eq!(c.kani_assume, 1);
    assert_eq!(c.verus_assume, 1);
    assert_eq!(c.external_body, 1);
    assert_eq!(c.assume_spec, 1);
}
